"""Render results/analysis.json + conformal.json + finetune/*.json + verbal + latency into results/tables.md.
  python3 -I tables.py
"""
import glob
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np

from analyze import JOBS, NAMES
from common import RES, wilson

A = json.load(open(f"{RES}/analysis.json"))
C = json.load(open(f"{RES}/conformal.json")) if os.path.exists(f"{RES}/conformal.json") else {}
out = []
P = out.append


def f(x, d=3):
    return "–" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{d}f}"


def ci(c):
    return f"[{c[0]:.2f}–{c[1]:.2f}]" if c else ""


P("# Sandbox tables (generated by scripts/tables.py)\n")
P("Test = BrainBench v0.2 world s2; label pool = worlds s1 (+ s3 for J1). 95% CIs: cluster bootstrap over test groups (tasks for J2/J3, entities for J1). AUROC-err = how well (1 − confidence) ranks the model's own wrong answers (0.5 = useless). Latency = batch-1 p50 on 1 contended vCPU, fp32.\n")

for job in ["J1", "J2", "J3t", "J3a", "J4"]:
    if job not in A:
        continue
    P(f"\n## {JOBS[job]}\n")
    P("### Zero-shot (no labels) and calibration-only with 200 labels\n")
    P("| model | n (groups) | zero-shot acc | ECE raw | AUROC-err raw | AUROC P(yes) | acc after T(200) | ECE after T(200) | Brier T(200) | ECE Platt(200) | acc Platt(200) | ECE isotonic(200) | p50 ms |")
    P("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for m, r in A[job].items():
        z = r["zero_shot_raw"]
        c200 = r.get("curve", {}).get("200", {})
        t = c200.get("temperature", {})
        pl = c200.get("platt", {})
        iso = c200.get("isotonic", {})
        g = lambda d, k: d.get(k, (None,))[0] if d else None
        P(f"| {NAMES.get(m, m)} | {z['n']} ({z['n_groups']}) | {f(z['acc'])} {ci(z['acc_ci'])} | {f(z['ece'])} | {f(z['auroc_err'])} | "
          f"{f(z.get('auroc'))} {ci(z.get('auroc_ci'))} | {f(g(t, 'acc'))} | {f(g(t, 'ece'))} | {f(g(t, 'brier'))} | {f(g(pl, 'ece'))} | {f(g(pl, 'acc'))} | {f(g(iso, 'ece'))} | {f(r.get('latency_p50_ms'), 0)} |")
    if job != "J3t" and job != "J3a" and any("zero_shot_shipped_T" in r for r in A[job].values()):
        r = A[job]["laya"]["zero_shot_shipped_T"]
        P(f"\nLaya with its shipped temperature: acc {f(r['acc'])}, ECE {f(r['ece'])}, Brier {f(r['brier'])}.\n")
    P("\n### Self-learning curve: linear head on frozen features + zero-shot logits (mean over 5 group-level resamples; [min–max])\n")
    P("| model | N=50 acc | N=50 ECE | N=200 acc | N=200 ECE | N=max acc | N=max ECE | N=max Brier | N=max AUROC-err | N=max acc 95% CI |")
    P("|---|---|---|---|---|---|---|---|---|---|")
    for m, r in A[job].items():
        cv = r.get("curve", {})
        if not cv:
            continue
        ks = sorted(cv, key=int)
        row = []
        for k in ["50", "200", ks[-1]]:
            h = cv.get(k, {}).get("linear_head")
            row += [f"{f(h['acc'][0])} [{h['acc'][1]:.2f}–{h['acc'][2]:.2f}]" if h else "–", f(h["ece"][0]) if h else "–"]
        hm = cv[ks[-1]].get("linear_head", {})
        hci = cv[ks[-1]].get("linear_head_ci", {})
        P(f"| {NAMES.get(m, m)} (max N={ks[-1]}) | {row[0]} | {row[1]} | {row[2]} | {row[3]} | {row[4]} | {row[5]} | "
          f"{f(hm.get('brier', (None,))[0])} | {f(hm.get('auroc_err', (None,))[0])} | {ci(hci.get('acc_ci'))} |")

# native head fine-tuning
fts = sorted(glob.glob(f"{RES}/finetune/*.json"))
if fts:
    P("\n## Native decision-head fine-tuning (frozen encoder, CE + 0.5·Brier, temperature on a 20% slice of the same label budget)\n")
    P("| run | N | reps | acc (mean [min–max]) | ECE | Brier | AUROC-err | train s |")
    P("|---|---|---|---|---|---|---|---|")
    for p in fts:
        d = json.load(open(p))
        tag = os.path.basename(p)[:-5]
        zs = d.get("zero_shot_check", {})
        P(f"| {tag} (zero-shot check) | 0 | – | {f(zs.get('acc'))} | {f(zs.get('ece'))} | {f(zs.get('brier'))} | {f(zs.get('auroc_err'))} | – |")
        for N, runs in sorted(d["runs"].items(), key=lambda kv: int(kv[0])):
            a = [x["cal"]["acc"] for x in runs]
            P(f"| {tag} | {N} | {len(runs)} | {f(np.mean(a))} [{min(a):.2f}–{max(a):.2f}] | {f(np.mean([x['cal']['ece'] for x in runs]))} | "
              f"{f(np.mean([x['cal']['brier'] for x in runs]))} | {f(np.mean([x['cal']['auroc_err'] for x in runs]))} | {np.mean([x['train_s'] for x in runs]):.0f} |")

# verbal
vp = f"{RES}/verbal_qwen06.json"
if os.path.exists(vp):
    V = json.load(open(vp))
    P("\n## Verbalised confidence baseline (Qwen3-0.6B greedy, 'ANSWER; CONFIDENCE 0-100')\n")
    P("| set | n | parsed | acc (parsed) | mean stated conf | ECE (stated conf vs correct) | AUROC-err | s/row |")
    P("|---|---|---|---|---|---|---|---|")
    from common import auroc
    for s, d in V.items():
        recs = d["recs"]
        ok = [x for x in recs if x["pred"] is not None and x["conf"] is not None]
        if not ok:
            continue
        corr = np.array([x["pred"] == x["label"] for x in ok], float)
        conf = np.array([x["conf"] for x in ok])
        bins = np.linspace(0, 1, 11)
        e = sum(((conf > a) & (conf <= b)).mean() * abs(conf[(conf > a) & (conf <= b)].mean() - corr[(conf > a) & (conf <= b)].mean())
                for a, b in zip(bins[:-1], bins[1:]) if ((conf > a) & (conf <= b)).any())
        P(f"| {s} | {len(recs)} | {len(ok)} | {f(corr.mean())} | {f(conf.mean(), 2)} | {f(e)} | {f(auroc(1 - conf, 1 - corr))} | {d['s_per_row']:.1f} |")

# conformal / integration
if C:
    P("\n## Brain integration analyses (pool split 2/3 fit, 1/3 calibration; test = world s2)\n")
    if "J1_deterministic_value_check" in C:
        d = C["J1_deterministic_value_check"]
        P(f"Deterministic value-token check alone: passes {f(d['pass_true'])} of true records; catches {', '.join(f'{k} {v:.2f}' for k, v in d['catch_by_kind'].items())}.\n")
    P("### J1 write gate: auto-accept iff P(supported) ≥ τ, τ by Learn-then-Test (95% CP bound on error among accepted ≤ ε)\n")
    P("| arm | ε | mode | automation (all) | auto-accepted true records | error among accepted (test) | 95% UCB | catch: numeric / swap / entity / attribute |")
    P("|---|---|---|---|---|---|---|---|")
    for arm, r in C.get("J1_gate", {}).items():
        for e in ["eps=0.02", "eps=0.05", "eps=0.1"]:
            if e not in r:
                continue
            for mode in ["model_only", "hybrid"]:
                x = r[e][mode]
                cb = x["catch_by_kind"]
                P(f"| {arm} | {e[4:]} | {mode} | {f(x['automation'])} | {f(x['auto_true'])} | {f(x['err_among_accepted'])} ({x['n_accepted']}) | {f(x['err_ucb95'])} | "
                  f"{f(cb.get('value_numeric'),2)} / {f(cb.get('value_swap'),2)} / {f(cb.get('entity_swap'),2)} / {f(cb.get('attribute_swap'),2)} |")
    P("\n### J1 risk–coverage on test (no certification): error rate among the top-q% most confident 'supported' calls\n")
    P("| arm | model-only @50% err: top10 / top25 / top50 | hybrid @50% err | model-only @10% err | hybrid @10% err |")
    P("|---|---|---|---|---|")
    for arm, r in C.get("J1_selective", {}).items():
        cell = lambda k: " / ".join(f"{r[k][q]:.3f}" for q in ["top10%", "top25%", "top50%"])
        P(f"| {arm} | {cell('model_only@prev0.5')} | {cell('hybrid@prev0.5')} | {cell('model_only@prev0.1')} | {cell('hybrid@prev0.1')} |")
    P("\n### J1 write gate at a realistic 10% extraction-error prevalence (errors subsampled in calibration and test; 30 draws)\n")
    P("| arm | ε | mode | LTT certified (share of draws) | automation | auto-accepted true records | realised error among accepted | catch: numeric / swap / entity / attribute |")
    P("|---|---|---|---|---|---|---|---|")
    for arm, r in C.get("J1_gate_prev10", {}).items():
        for e in ["eps=0.02", "eps=0.05"]:
            for mode in ["model_only", "hybrid"]:
                x = r[e][mode]
                cb = x["catch_by_kind"]
                P(f"| {arm} | {e[4:]} | {mode} | {f(x['certified_share'],2)} | {f(x['automation'])} | {f(x['auto_true'])} | {f(x['err_among_accepted'])} | "
                  f"{f(cb.get('value_numeric'),2)} / {f(cb.get('value_swap'),2)} / {f(cb.get('entity_swap'),2)} / {f(cb.get('attribute_swap'),2)} |")
    P("\n### J2 certified recall of vital candidates per task (conformal on min P(vital) over the task's vital items)\n")
    P("| arm | α | λ | cal tasks | test tasks | coverage [Wilson] | CP lower 95% | kept fraction of candidates |")
    P("|---|---|---|---|---|---|---|---|")
    for arm, r in C.get("J2_recall", {}).items():
        for a, x in r.items():
            P(f"| {arm} | {x['alpha']} | {f(x['lam'])} | {x['n_cal_tasks']} | {x['n_test_tasks']} | {f(x['coverage'])} {ci(x['coverage_wilson'])} | {f(x['coverage_cp_lower95'])} | {f(x['kept_fraction'])} |")
    for sub in ["J3t", "J3a"]:
        P(f"\n### {JOBS[sub]}: split-conformal prediction sets\n")
        P("| arm | α | coverage [Wilson] | mean set size | singleton share | singleton accuracy |")
        P("|---|---|---|---|---|---|")
        for arm, r in C.get(f"{sub}_sets", {}).items():
            for a, x in r.items():
                P(f"| {arm} | {x['alpha']} | {f(x['coverage'])} {ci(x['coverage_wilson'])} | {f(x['mean_set'],2)} | {f(x['singleton'])} | {f(x['singleton_acc'])} |")


# stacking / diversity (J1)
sp = f"{RES}/stack_J1.json"
if os.path.exists(sp):
    S = json.load(open(sp))
    P("\n## J1 checker diversity: logistic stack of zero-shot margins + deterministic value check (fit on N pool labels)\n")
    P("| N | signals | acc | ECE | Brier | AUROC P(supported) | catch: numeric / swap / entity / attribute |")
    P("|---|---|---|---|---|---|---|")
    for k, v in S.items():
        if not k.startswith("N="):
            continue
        n, sig = k.split("|")
        cb = v.get("catch_by_kind", {})
        P(f"| {n[2:]} | {sig} | {f(v['acc'])} | {f(v['ece'])} | {f(v['brier'])} | {f(v.get('auroc'))} | "
          f"{f(cb.get('value_numeric'),2)} / {f(cb.get('value_swap'),2)} / {f(cb.get('entity_swap'),2)} / {f(cb.get('attribute_swap'),2)} |")
    P("\nZero-shot error overlap (threshold 0): " + "; ".join(f"{k.split('|')[1]} vs {k.split('|')[2]}: errors {v['err_a']} / {v['err_b']}, both wrong {v['both']}, margin corr {v['corr_margins']:.2f}" for k, v in S.items() if k.startswith("overlap|")) + "\n")

open(f"{RES}/tables.md", "w").write("\n".join(out) + "\n")
print("\n".join(out)[:3000])
